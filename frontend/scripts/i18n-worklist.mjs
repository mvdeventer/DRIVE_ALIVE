#!/usr/bin/env node
/**
 * Regenerates docs/i18n-worklist.md from the live state of the codebase.
 *
 * Run it any time to refresh progress:
 *   npm --prefix frontend run i18n:worklist
 *
 * A hand-maintained checklist would drift the moment a file was touched. This
 * derives everything from i18n-detect-hardcoded --json plus the allowlist, so
 * the counts are always real.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { execFileSync } from 'node:child_process';

const ROOT = process.cwd();                       // frontend/
const REPO = path.resolve(ROOT, '..');
const OUT = path.join(REPO, 'docs', 'i18n-worklist.md');

/**
 * Screens rendered inside <LocaleOverride locale="en"> in App.tsx. They always
 * display English by design, so extracting their strings would be pure churn.
 */
const ALWAYS_ENGLISH = {
  'screens/auth/LoginScreen.tsx': 'Sign-in — no user identified yet',
  'screens/auth/SetupScreen.tsx': 'First-run wizard — no account exists yet',
};

const GROUPS = [
  ['Student — what learners see', (p) => p.includes('/student/')],
  ['Booking & payment', (p) => p.includes('/booking/') || p.includes('/payment/')],
  ['Instructor', (p) => p.includes('/instructor/')],
  ['Admin', (p) => p.includes('/admin/')],
  ['Sign-up & verification', (p) => p.includes('/auth/') || p.includes('/verification/')],
  ['Shared components', (p) => p.startsWith('components/')],
  ['Navigation', (p) => p.startsWith('navigation/')],
  ['Other', () => true],
];

function detect() {
  const raw = execFileSync('node', ['./scripts/i18n-detect-hardcoded.mjs', '--json'], {
    cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024,
  });
  return JSON.parse(raw);
}

function allowlistedPaths() {
  const p = path.join(ROOT, 'i18n', 'hardcoded-allowlist.json');
  const d = JSON.parse(fs.readFileSync(p, 'utf8'));
  return d.ignorePathRegexes ?? [];
}

function listSourceFiles() {
  const out = [];
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) { walk(full); continue; }
      if (!/\.(tsx?|jsx?)$/.test(e.name)) continue;
      if (full.includes('__tests__') || e.name.endsWith('.d.ts')) continue;
      out.push(path.relative(ROOT, full).split(path.sep).join('/'));
    }
  };
  ['screens', 'components', 'navigation'].forEach((d) => walk(path.join(ROOT, d)));
  return out;
}

function main() {
  const { perFile } = detect();
  const allow = allowlistedPaths();
  const isAllowlisted = (f) => allow.some((rx) => new RegExp(rx).test(f));

  const files = listSourceFiles().filter((f) => {
    const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
    return (perFile[f] ?? 0) > 0 || /\bt\('/.test(src);
  });

  const rows = files.map((f) => {
    const remaining = perFile[f] ?? 0;
    const skip = ALWAYS_ENGLISH[f];
    let status;
    if (skip) status = 'skip';
    else if (remaining === 0 && !isAllowlisted(f)) status = 'done';
    else status = 'todo';
    return { file: f, remaining, status, skip };
  });

  const todo = rows.filter((r) => r.status === 'todo');
  const done = rows.filter((r) => r.status === 'done');
  const skipped = rows.filter((r) => r.status === 'skip');
  const outstanding = todo.reduce((n, r) => n + r.remaining, 0);
  const skipCount = skipped.reduce((n, r) => n + r.remaining, 0);

  const L = [];
  L.push('# Afrikaans translation worklist');
  L.push('');
  L.push('> Generated by `npm --prefix frontend run i18n:worklist` — do not hand-edit.');
  L.push('> Re-run it to refresh progress.');
  L.push('');
  L.push('Every user-facing string must come from `t()` so it follows the account');
  L.push("language. A file is **done** when it has zero detector findings *and* its");
  L.push('entry has been removed from `i18n/hardcoded-allowlist.json`.');
  L.push('');
  L.push('| | Count |');
  L.push('|---|---|');
  L.push(`| Strings still to translate | **${outstanding}** |`);
  L.push(`| Files remaining | ${todo.length} |`);
  L.push(`| Files complete | ${done.length} |`);
  L.push(`| Deliberately English (see below) | ${skipCount} strings |`);
  L.push('');

  if (skipped.length) {
    L.push('## Deliberately left in English');
    L.push('');
    L.push('Wrapped in `<LocaleOverride locale="en">` in `App.tsx` — they render');
    L.push('English whatever the user picks, so translating them changes nothing.');
    L.push('');
    for (const r of skipped) L.push(`- \`${r.file}\` (${r.remaining}) — ${r.skip}`);
    L.push('');
  }

  L.push('## Remaining work');
  L.push('');
  L.push('Ordered by audience: the screens most users see come first, and the');
  L.push('2,500-line `DatabaseInterfaceScreen` comes last because it is the');
  L.push('riskiest file in the repo.');
  L.push('');

  const claimed = new Set();
  for (const [title, match] of GROUPS) {
    const group = todo
      .filter((r) => !claimed.has(r.file) && match(r.file))
      .sort((a, b) => b.remaining - a.remaining);
    group.forEach((r) => claimed.add(r.file));
    if (!group.length) continue;
    const total = group.reduce((n, r) => n + r.remaining, 0);
    L.push(`### ${title} — ${total} strings`);
    L.push('');
    for (const r of group) L.push(`- [ ] \`${r.file}\` — ${r.remaining}`);
    L.push('');
  }

  if (done.length) {
    L.push('## Complete');
    L.push('');
    for (const r of done.sort((a, b) => a.file.localeCompare(b.file))) {
      L.push(`- [x] \`${r.file}\``);
    }
    L.push('');
  }

  L.push('---');
  L.push('');
  L.push(`_Last generated: ${new Date().toISOString().slice(0, 16).replace('T', ' ')}_`);

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, L.join('\n') + '\n', 'utf8');
  process.stdout.write(
    `Wrote ${path.relative(REPO, OUT)} — ${outstanding} strings across ${todo.length} file(s); ${done.length} complete.\n`,
  );
}

main();
